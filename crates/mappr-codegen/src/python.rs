//! The Python script: its header and configuration block (PyMappr's
//! `export/python_script.py`), above the template pasted verbatim.

use crate::config::{Config, InsetConfig, Layer};
use crate::lit::{Lit, comment_text, py, round_to, safe_name, wrapped_items};

pub const TEMPLATE: &str = include_str!("../templates/recreate_map.py");

pub const REQUIREMENTS: &str = "geopandas>=1.0\nmatplotlib>=3.8\nnumpy>=1.26\npandas>=2.1\n";
pub const GITIGNORE: &str = "naturalearth_cache/\nmap.png\n__pycache__/\n";

fn header(c: &Config) -> String {
    let mut notes: String = c.notes.iter().map(|n| format!("\n#   - {n}")).collect();
    if !notes.is_empty() {
        notes = format!("\n# Shown in PyMappr but NOT reproduced by this script:{notes}");
    }
    let data_note = if c.data_files {
        "Your point data is in the data/ folder as CSV - edit or replace those files\nto update the map."
    } else {
        "Your point data is embedded below in DATASETS, so this single file is\nself-contained - nothing else to download or keep alongside it."
    };
    let generator = &c.generator;
    let project = safe_name(&c.project).replace('\\', "\\\\");
    format!(
        "#!/usr/bin/env python3
# Made with {generator} - {repo}
\"\"\"Recreate the PyMappr map \"{project}\" outside PyMappr.

Generated by {generator} from pre-made function templates and
the map's saved settings

Just run it: open this file in an IDE (PyCharm, VS Code, ...) and click
Run, or `python recreate_map.py` in a terminal. If a package it needs
(pandas, geopandas, matplotlib) is missing, it prints the pip command to
install it - or run `python recreate_map.py --install-deps` to have it
installed for you. The map data is downloaded from Natural Earth and cached
in naturalearth_cache/ next to this script.

Output:  map.png (also opens an interactive window).

{data_note}
\"\"\"
# Projection: {projection}{notes}
",
        repo = c.repo_url,
        projection = c.projection,
    )
}

fn layer_entry(layer: &Layer) -> Lit {
    let mut entry: Vec<(&str, Lit)> = vec![
        ("name", Lit::str(&layer.name)),
        ("category", Lit::str(&layer.category)),
        ("scale", Lit::str(&layer.scale)),
        ("kind", Lit::str(&layer.kind)),
        ("z", Lit::Float(crate::lit::round6(layer.z))),
        ("color", layer.color.clone()),
    ];
    if let Some(member) = layer.member.as_ref().filter(|m| !m.is_empty()) {
        entry.push(("member", Lit::str(member)));
    }
    if layer.filter.truthy() {
        entry.push(("filter", layer.filter.clone()));
    }
    match layer.kind.as_str() {
        "fill" => {
            entry.push(("edgecolor", layer.edgecolor.clone()));
            entry.push(("width", Lit::Float(round_to(layer.width, 3))));
            entry.push(("alpha", Lit::Float(layer.alpha)));
        }
        "line" | "continents" => {
            entry.push(("width", Lit::Float(round_to(layer.width, 3))));
            entry.push(("linestyle", layer.linestyle.clone()));
        }
        _ => {
            entry.push(("marker", Lit::str(&layer.marker)));
            entry.push(("size", Lit::Float(layer.size)));
            entry.push(("edgecolor", layer.edgecolor.clone()));
            if let Some(t) = layer.min_zoom_max {
                entry.push(("min_zoom_max", Lit::Float(t)));
            }
        }
    }
    Lit::dict(entry)
}

fn dict_body(lit: &Lit) -> String {
    let Lit::Dict(pairs) = lit else { return py(lit) };
    pairs.iter().map(|(k, v)| format!("{}: {}", py(k), py(v))).collect::<Vec<_>>().join(", ")
}

fn config_block(c: &Config) -> String {
    let mut l: Vec<String> = vec![
        String::new(),
        "# ------------------------- map configuration (from PyMappr) -------------------------".into(),
        String::new(),
    ];
    l.push(format!("MAP_CRS = {}  # proj4 string, or None for plain lon/lat degrees", py(&Lit::opt_str(c.crs.as_deref()))));
    let p = &c.proj;
    l.push(format!(
        "PROJ = {{'bounds': {}, 'max_lat': {}, 'min_lat': {}, 'lon_0': {}, 'lon_halfspan': {}, 'hemisphere': {}}}",
        py(&Lit::floats(&p.bounds.map(crate::lit::round6))),
        py(&Lit::Float(p.max_lat)),
        py(&Lit::Float(p.min_lat)),
        py(&Lit::Float(p.lon_0)),
        py(&Lit::Float(p.lon_halfspan)),
        py(&Lit::Bool(p.hemisphere)),
    ));
    l.push(format!(
        "CLIP_CAP = {}  # (lon0, lat0, radius) visible cap for the globe, else None",
        c.clip_cap.map_or("None".into(), |cap| py(&Lit::floats(&cap)))
    ));
    l.push(format!("VIEW = {}  # axis limits in map coordinates (x0, x1, y0, y1)", py(&Lit::floats(&c.view))));
    l.push(format!("ZOOM = {}  # log2(world width / view width), used for culling", py(&Lit::Float(c.zoom))));
    l.push(format!("FIGSIZE = {}  # inches; the app canvas geometry", py(&Lit::floats(&[c.figsize.0, c.figsize.1]))));
    l.push(format!("MARGINS = {}  # axes box as figure fractions (l, b, r, t)", py(&Lit::floats(&c.margins))));
    l.push(format!("BASEMAP = {}  # raster basemap mode (\"simple\" = none)", py(&Lit::str(&c.basemap))));
    l.push(format!(
        "GRATICULE = {{'interval': {}, 'labels': {}}}",
        py(&Lit::opt_float(c.graticule)),
        py(&Lit::Bool(c.grid_labels))
    ));
    l.push(format!("COMPASS = {}", py(&c.compass_options.to_lit())));
    l.push(format!("SCALE_BAR = {}", py(&c.scale_bar.to_lit())));
    l.push(format!("POINT_ALPHA = {}", py(&Lit::Float(c.point_alpha))));
    l.push(format!(
        "POINT_EDGE = {}  # outline around filled markers",
        py(&Lit::dict(vec![("color", Lit::str(&c.point_edge.0)), ("width", Lit::Float(c.point_edge.1))]))
    ));
    l.push(format!("DPI = {}", py(&Lit::Int(c.dpi))));
    l.push("OUTPUT_FILE = \"map.png\"".into());
    l.push(String::new());
    l.push("# Natural Earth layers enabled in PyMappr, with the renderer's true draw".into());
    l.push("# order (z). A filter is (column, kept values, keep?) applied after download.".into());
    l.push("LAYERS = [".into());
    for layer in &c.layers {
        l.push(format!("    # PyMappr layer: {}", layer.key));
        l.push(format!("    {{{}}},", dict_body(&layer_entry(layer))));
    }
    l.push("]".into());
    l.push(String::new());
    l.push("# Map label layers (country/city/... names), like the app draws them.".into());
    l.push("LABEL_LAYERS = [".into());
    for spec in &c.label_layers {
        l.push(format!("    {{{}}},", dict_body(spec)));
    }
    l.push("]".into());
    l.push(String::new());
    l.push("# One entry per dataset. lon_col/lat_col name the coordinate columns".into());
    l.push("# (None = auto-detect by column name).".into());
    l.push("# label_map renames groups for the legend; 'styles' maps each group to its".into());
    l.push("# point style, in render order (open = outline-only marker).".into());
    l.push("DATASETS = [".into());
    for spec in &c.datasets {
        if let Some(source) = &spec.source {
            l.push(format!("    # originally imported from: {}", comment_text(source)));
        }
        l.push("    {".into());
        let label_map = Lit::Dict(spec.label_map.iter().map(|(k, v)| (Lit::str(k), Lit::str(v))).collect());
        let fields: [(&str, Lit); 12] = [
            ("name", Lit::str(&spec.name)),
            ("path", Lit::opt_str(spec.path.as_deref())),
            ("inline_data", Lit::opt_str(spec.inline_data.as_deref())),
            ("lon_col", Lit::str("Longitude")),
            ("lat_col", Lit::str("Latitude")),
            ("group_col", Lit::opt_str(spec.group_col.as_deref())),
            ("color_col", Lit::opt_str(spec.color_col.as_deref())),
            ("symbol_col", Lit::opt_str(spec.symbol_col.as_deref())),
            ("default_label", Lit::str("All points")),
            ("label_map", label_map),
            ("open_col", Lit::opt_str(spec.open_col.as_deref())),
            ("open_values", Lit::List(spec.open_values.iter().map(Lit::str).collect())),
        ];
        for (key, value) in fields {
            l.push(format!("        {}: {},", py(&Lit::str(key)), py(&value)));
        }
        l.push("        'styles': {".into());
        for (value, style) in &spec.styles {
            l.push(format!("            {}: {},", py(&Lit::str(value)), py(&style.to_lit())));
        }
        l.push("        },".into());
        l.push("    },".into());
    }
    l.push("]".into());
    l.push(String::new());
    match &c.legend_sections {
        None => l.push("LEGEND_SECTIONS = None  # plain legend: one row per style, in DATASETS".into()),
        Some(sections) => {
            l.push("# Sectioned legend, like the app's: (label, style, depth) rows, where".into());
            l.push("# depth indents a row under the one above it (a nested genus/species key).".into());
            l.push("LEGEND_SECTIONS = [".into());
            for (title, rows) in sections {
                l.push(format!("    ({}, [", py(&Lit::str(title))));
                for (label, style, depth) in rows {
                    let drawn = style.as_ref().map_or("None".into(), |s| py(&s.to_lit()));
                    l.push(format!("        ({}, {drawn}, {depth}),", py(&Lit::str(label))));
                }
                l.push("    ]),".into());
            }
            l.push("]".into());
        }
    }
    l.push(String::new());
    l.push("# Legend rows for the plain legend, in order (None = every style, in DATASETS order).".into());
    l.push(format!(
        "LEGEND_ROWS = {}",
        c.legend_rows.as_ref().map_or("None".into(), |rows| py(&Lit::List(rows.iter().map(Lit::str).collect())))
    ));
    l.push(String::new());
    l.push("# The legend's last row: what the open symbols mark (None = no open symbols).".into());
    match &c.open_note {
        None => l.push("OPEN_NOTE = None".into()),
        Some((label, style)) => l.push(format!("OPEN_NOTE = ({}, {})", py(&Lit::str(label)), py(&style.to_lit()))),
    }
    l.push(String::new());
    l.push(format!("LEGEND = {{{}}}", dict_body(&c.legend.to_lit())));
    l.push(String::new());
    l.extend(inset_lines(c.inset.as_ref()));
    l.join("\n") + "\n"
}

fn values(values: &[Option<f64>]) -> Vec<String> {
    values.iter().map(|v| py(&Lit::opt_float(*v))).collect()
}

fn inset_lines(inset: Option<&InsetConfig>) -> Vec<String> {
    let mut l: Vec<String> = [
        "# The inset map, as PyMappr drew it (None = no inset): rect is its place in the",
        "# map's axes fraction (x, y, width, height), limits its axis limits in its own",
        "# CRS (None = plain lon/lat), clip_cap / band what layers are clipped to before",
        "# reprojecting, and box the outline linking the two maps, drawn on the inset",
        "# or on the main map (None in x/y breaks the line).",
    ]
    .map(String::from)
    .to_vec();
    let Some(i) = inset else {
        l.push("INSET = None".into());
        return l;
    };
    l.push("INSET = {".into());
    let floats = |v: &[f64]| Lit::List(v.iter().map(|x| Lit::Float(*x)).collect());
    let fields: Vec<(&str, Lit)> = vec![
        ("projection", Lit::str(&i.projection)),
        ("crs", Lit::opt_str(i.crs.as_deref())),
        ("rect", floats(&i.rect)),
        ("lon_0", Lit::Float(i.lon_0)),
        ("lat_0", Lit::Float(i.lat_0)),
        ("min_lat", Lit::Float(i.min_lat)),
        ("max_lat", Lit::Float(i.max_lat)),
        ("lon_halfspan", Lit::Float(i.lon_halfspan)),
        ("hemisphere", Lit::Bool(i.hemisphere)),
        ("clip_cap", i.clip_cap.map_or(Lit::None, |c| Lit::floats(&c))),
        ("band", i.band.map_or(Lit::None, |b| Lit::floats(&b))),
        ("limits", floats(&i.limits)),
        ("zoom", Lit::Float(i.zoom)),
        ("points", Lit::Bool(i.points)),
        ("point_scale", Lit::Float(i.point_scale)),
        ("frame_width", Lit::Float(i.frame_width)),
        ("clear", i.clear.as_ref().map_or(Lit::None, |(corner, y)| Lit::Tuple(vec![Lit::str(corner), Lit::Float(*y)]))),
    ];
    for (key, value) in fields {
        l.push(format!("    {}: {},", py(&Lit::str(key)), py(&value)));
    }
    l.push("    'layers': [".into());
    for layer in &i.layers {
        l.push(format!("        # PyMappr inset layer: {}", layer.key));
        l.push(format!("        {{{}}},", dict_body(&layer_entry(layer))));
    }
    l.push("    ],".into());
    match &i.horizon {
        None => l.push("    'horizon': None,".into()),
        Some(horizon) => {
            l.push("    # The globe's horizon (x list, y list).".into());
            l.push("    'horizon': (".into());
            for v in horizon {
                l.push("        [".into());
                l.extend(wrapped_items(&values(v), &" ".repeat(12), 78));
                l.push("        ],".into());
            }
            l.push("    ),".into());
        }
    }
    match &i.boxed {
        None => l.push("    'box': None,".into()),
        Some(b) => {
            l.push(format!(
                "    'box': {{'target': {}, 'color': {}, 'width': {},",
                py(&Lit::str(&b.target)),
                py(&Lit::str(&b.color)),
                py(&Lit::Float(b.width))
            ));
            for (axis, v) in [("x", &b.x), ("y", &b.y)] {
                l.push(format!("            {}: [", py(&Lit::str(axis))));
                l.extend(wrapped_items(&values(v), &" ".repeat(16), 78));
                l.push("            ],".into());
            }
            l.push("    },".into());
        }
    }
    l.push("}".into());
    l
}

pub fn script(c: &Config) -> String {
    header(c) + &config_block(c) + TEMPLATE
}

