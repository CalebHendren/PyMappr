r"""Write projection reference values for mappr-core's tests.

Run with PyMappr's environment so the PROJ strings come from PyMappr itself:

    C:\PyCharm\PyMappr\.venv\Scripts\python.exe scripts/pyproj_reference.py C:\PyCharm\PyMappr
"""

import sys
from pathlib import Path

sys.path.insert(0, sys.argv[1])

from pyproj import Transformer  # noqa: E402

from pymappr.geo.projections import (LAMBERT_DEFS, PROJECTIONS,  # noqa: E402
                                     default_origin, is_globe, proj4_string)

OUT = Path(__file__).resolve().parent.parent / "crates/mappr-core/tests/data/pyproj_reference.txt"

lines = ["# name\tlon\tlat\tx\ty  (generated by scripts/pyproj_reference.py)"]
for name in PROJECTIONS:
    crs = proj4_string(name)
    if crs is None:
        continue
    to = Transformer.from_crs("EPSG:4326", crs, always_xy=True)
    if is_globe(name) or name in LAMBERT_DEFS:
        lon0, lat0 = default_origin(name)
        offsets = [(-40, -30), (-10, 5), (0, 0), (15, 20), (35, -15), (60, 25)]
        samples = [(lon0 + a, max(-89.0, min(89.0, lat0 + b))) for a, b in offsets]
    else:
        samples = [(lon, lat) for lon in (-180, -120, -45, 0, 30, 179.5)
                   for lat in (-85, -60, -12.5, 0, 33.3, 70)]
    for lon, lat in samples:
        x, y = to.transform(lon, lat)
        lines.append(f"{name}\t{lon}\t{lat}\t{x!r}\t{y!r}")

OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {len(lines) - 1} rows to {OUT}")
